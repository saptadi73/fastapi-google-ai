"""Build error tables for docs, bounded knowledge articles and the static frontend."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GROUPS = {
    "sumber": ("Sumber Google Sheets dan discovery", ["/sources", "/workspace", "/jobs"]),
    "review": ("Review konfigurasi dan deploy schema", ["/etl-review/*", "/configurations/*", "/release-approvals", "/jobs"]),
    "import": ("Validasi data dan batch import", ["/import-reviews", "/import-reviews/*", "/workspace", "/quality"]),
    "akses": ("Akses pengguna dan katalog data", ["/admin", "/admin/users", "/access-requests", "/data-catalog", "/dashboard"]),
    "layanan": ("Layanan database dan AI", ["/jobs", "/system", "/dashboard", "/chat"]),
}
INTRO = (
    "Cari kode pada pesan error atau monitor job; catat ID job, sumber/tab dan versi konfigurasi. "
    "Penyebab di bawah adalah kemungkinan, bukan diagnosis otomatis. "
    "Baca detail/log untuk menentukan kasus yang terjadi. "
    "DEFAULT_DENY, EXPLICIT_DENY dan ACTION_NOT_GRANTED adalah reason_code keputusan akses; "
    "TYPE_OR_NULL_ERROR/DUPLICATE_BUSINESS_KEY adalah temuan validasi; "
    "AI_REVIEW_ISSUES/AI_REVIEW_NOT_IMPLEMENTED adalah blocker checkpoint. "
    "Kode tersebut tidak selalu muncul sebagai error HTTP. "
    "NEEDS_INPUT berarti menunggu tindakan, bukan worker sedang berjalan. "
    "Muat ulang halaman hanya membaca status; tidak menjalankan discovery, profiling atau sync. "
    "Jangan kirim password, token, API key atau nilai pribadi ke helper."
)


def table(rows):
    result = ["| Kode / respons | Kemungkinan penyebab | Tindakan yang dilakukan |", "| --- | --- | --- |"]
    for row in rows:
        result.append(f"| `{row['code']}` | {row['cause']} | {row['action']} |")
    return "\n".join(result)


def documents(frontend_root=None):
    raw = (ROOT / "docs/error-responses.json").read_text(encoding="utf-8")
    rows = json.loads(raw)
    if len({row["code"] for row in rows}) != len(rows):
        raise ValueError("Duplicate error codes")
    result = {}
    sections = []
    for index, (group, (title, routes)) in enumerate(GROUPS.items(), 14):
        selected = [row for row in rows if row["group"] == group]
        body = INTRO + "\n\n" + table(selected) + "\n"
        if len(body.strip()) > 6000:
            raise ValueError(f"Knowledge article exceeds provider limit: {group}")
        header = (
            f"---\nid: error-response-{group}\ntitle: Error response - {title}\n"
            f"summary: Tabel penyebab dan tindakan untuk {', '.join(row['code'] for row in selected)}.\n"
            f"routes: {json.dumps(routes + ['/guide'])}\naudiences: [\"*\"]\n"
            "source: docs/ERROR_RESPONSES.md\n---\n"
        )
        result[ROOT / f"docs/knowledge/{index:02}-error-response-{group}.md"] = header + body
        sections.append(f"## {title}\n\n{table(selected)}")
    full = (
        "# Error response: penyebab dan tindakan\n\n"
        "<!-- Generated by scripts/export_error_reference.py from docs/error-responses.json. -->\n\n"
        + INTRO + "\n\n" + "\n\n".join(sections)
        + "\n\nDi aplikasi, buka **Bantuan > Tabel error response**, atau **Panduan lengkap > Tabel error response**. "
        "Cari kode, penyebab atau tindakan. Tombol **Temukan tab** di Workspace menjalankan discovery ulang; "
        "tunggu SUCCEEDED sebelum **Profiling ulang**. Tombol ini memerlukan SOURCE_OWNER, DATA_STEWARD atau PLATFORM_ADMIN.\n"
    )
    result[ROOT / "docs/ERROR_RESPONSES.md"] = full
    if frontend_root:
        result[frontend_root / "docs/ERROR_RESPONSES.md"] = full
        result[frontend_root / "src/content/errorResponses.json"] = raw
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--frontend-root", type=Path)
    args = parser.parse_args()
    outputs = documents(args.frontend_root)
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Error reference is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    print(f"Verified {len(outputs)} error reference documents.")


if __name__ == "__main__":
    main()
